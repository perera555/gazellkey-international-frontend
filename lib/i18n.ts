// Languages for the work visa pages (Work visa page, job pages, the apply
// form and My account > My work visa). The visitor's choice is kept in the
// "gk-lang" cookie. Job details typed by staff (title, description ...) are
// shown as entered. Add a language: add it to LANGUAGES and give every key.

export const LANGUAGES = [
  { code: "en", label: "English" },
  { code: "si", label: "සිංහල" },
  { code: "ta", label: "தமிழ்" },
  { code: "es", label: "Español" },
] as const;

export type Lang = (typeof LANGUAGES)[number]["code"];

export const LANG_COOKIE = "gk-lang";

export function toLang(value: string | undefined | null): Lang {
  return LANGUAGES.some((language) => language.code == value) ? (value as Lang) : "en";
}

// The announced-interview type of a job, in the visitor's language
export function interviewModeLabel(t: Dict, mode: string) {
  return mode == "WALK_IN" ? t.walkInMode : mode == "BY_INVITATION" ? t.invitationMode : t.onlineMode;
}

export function interviewModeText(t: Dict, mode: string) {
  return mode == "WALK_IN" ? t.walkInModeText : mode == "BY_INVITATION" ? t.invitationModeText : t.onlineModeText;
}

// "{count} jobs" -> "8 jobs"
export function fill(text: string, values: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ""));
}

